celsius = float(input("Enter temperature in Celsius:\n"))
# The user is asked to enter a temperature in Celsius, which is then stored as a float in the variable "celsius".
fahrenheit = 9 * celsius / 5 + 32
# The formula to convert celsius to fahrenheit is applied: (9/5) * celsius + 32, and the result is stored in the variable "fahrenheit".
print("Temperature in Fahrenheit:", fahrenheit)
# The calculated temperature in Fahrenheit is printed to the console.